// `npm run handoff:text`: the handoff as plain .txt files, for AI tools that won't accept a .zip.
// Every committed text file is written between "----- BEGIN FILE: path -----" / "----- END FILE: path -----" markers,
// grouped by area and split so no file exceeds MAX_BYTES. acc-00-START-HERE.txt holds the AI context, the index and a
// small script that rebuilds the folder from the parts. Only committed files are used (never data, keys or brand files).
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const MAX_BYTES = Number(process.env.ACC_HANDOFF_MAX_KB ?? 380) * 1024;
const git = (...a) => execFileSync("git", a, { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });
const sha = git("rev-parse", "--short", "HEAD").trim();
const files = git("ls-tree", "-r", "--name-only", "HEAD").trim().split("\n");

const SKIP = [
  /\.(png|jpe?g|gif|ico|woff2?|ttf|zip|pdf|pptx|xlsx)$/i, // binaries
  /^package-lock\.json$/, // regenerated by npm install (large)
  /^public\/.*\.svg$/, // framework sample icons
];
const BLOCK = [
  /^brand\/(?!README\.md$|\.gitkeep$|brand\.example\.json$)/,
  /(^|\/)\.env(?!\.example$)(\.|$)/,
  /\.(db|db-journal|sqlite|sqlite3|pem|key|p12)$/,
  /^(backups|exports|imports|handoff|screenshots)\//,
];
const bad = files.filter((f) => BLOCK.some((re) => re.test(f)));
if (bad.length) {
  console.error(
    `[acc] Refusing: the commit contains files that must stay local:\n  ${bad.join("\n  ")}`,
  );
  process.exit(1);
}

const GROUPS = [
  [
    "docs",
    (f) =>
      /^(CLAUDE|README|AGENTS|PROMPT[^/]*)\.md$/.test(f) ||
      f.startsWith("docs/") ||
      f.startsWith("brand/") ||
      f.startsWith("examples/"),
  ],
  [
    "setup-and-data-model",
    (f) =>
      !f.includes("/") ||
      f.startsWith("prisma/") ||
      f.startsWith("src/config/") ||
      f.startsWith("src/lib/domain/") ||
      f.startsWith(".github/") ||
      f.startsWith(".cursor/") ||
      f.startsWith(".githooks/"),
  ],
  ["lib", (f) => f.startsWith("src/lib/")],
  ["modules", (f) => f.startsWith("src/modules/")],
  ["app-and-components", (f) => f.startsWith("src/")],
  ["tests-and-scripts", () => true],
];

const text = files.filter((f) => !SKIP.some((re) => re.test(f)));
const assigned = new Map(GROUPS.map(([name]) => [name, []]));
for (const f of text) assigned.get(GROUPS.find(([, test]) => test(f))[0]).push(f);

const block = (f) => {
  const body = git("show", `HEAD:${f}`);
  // A file without a final newline is marked, so rebuilding restores it byte for byte.
  const nl = body.endsWith("\n");
  return `----- BEGIN FILE: ${f}${nl ? "" : " [no-final-newline]"} -----\n${body}${nl ? "" : "\n"}----- END FILE: ${f} -----\n\n`;
};

rmSync("handoff/text", { recursive: true, force: true });
mkdirSync("handoff/text", { recursive: true });
const parts = [];
for (const [name] of GROUPS) {
  let chunk = "";
  let list = [];
  let n = 1;
  const flush = () => {
    if (!list.length) return;
    const label = `${name}${n > 1 || chunk.length >= MAX_BYTES ? `-${n}` : ""}`;
    parts.push({ label, files: list, body: chunk });
    chunk = "";
    list = [];
    n++;
  };
  for (const f of assigned.get(name)) {
    const b = block(f);
    if (chunk.length + b.length > MAX_BYTES && list.length) flush();
    chunk += b;
    list.push(f);
  }
  flush();
}

const pad = (i) => String(i + 1).padStart(2, "0");
const names = parts.map((p, i) => `acc-${pad(i)}-${p.label}.txt`);
parts.forEach((p, i) => {
  const head =
    `ACCOUNT COMMAND CENTER: handoff part ${i + 1} of ${parts.length} (${p.label}), commit ${sha}\n` +
    `Files in this part: ${p.files.length}. Each file sits between BEGIN FILE / END FILE markers with its repository path.\n\n`;
  writeFileSync(`handoff/text/${names[i]}`, head + p.body);
});

const context = readFileSync("docs/AI_CONTEXT.md", "utf8");
const restore = `// rebuild.mjs: node rebuild.mjs acc-*.txt  →  recreates the repository folder "account-command-center/"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
for (const part of process.argv.slice(2)) {
  const t = readFileSync(part, "utf8");
  for (const m of t.matchAll(/^----- BEGIN FILE: (.+?)( \\[no-final-newline\\])? -----\\n([\\s\\S]*?)^----- END FILE: \\1 -----$/gm)) {
    const out = path.join("account-command-center", m[1]);
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, m[2] ? m[3].slice(0, -1) : m[3]);
  }
}
console.log("Rebuilt account-command-center/. Next: cd account-command-center && npm install && npm run setup");
`;
const start = `ACCOUNT COMMAND CENTER (ACC): HANDOFF, START HERE (commit ${sha})

This is the full source of ACC as plain text, for AI tools that don't accept .zip files. Contents:
code, tests and docs only; no customer data, database, backups, keys or brand files.

HOW TO USE
- Knowledge upload (agent platforms, "upload files" features): upload ALL acc-*.txt files, and give the
  assistant the "AI CONTEXT" section below as its instructions.
- Chat window with limited memory: paste the "AI CONTEXT" section as your first message, then attach only the
  part that covers your task (see the index).
- Rebuilding the actual folder (e.g. to put it in company Git): save the REBUILD SCRIPT below as rebuild.mjs
  next to the parts and run:  node rebuild.mjs acc-*.txt
  Then: npm install (package-lock.json is omitted; npm regenerates it) && npm run setup.

PARTS
${parts.map((p, i) => `- ${names[i]}: ${p.files.length} files (${Math.round(p.body.length / 1024)} KB): ${p.label}`).join("\n")}

=============================== AI CONTEXT ===============================
${context}
============================== REBUILD SCRIPT ==============================
${restore}`;
writeFileSync("handoff/text/acc-00-START-HERE.txt", start);
const total = parts.reduce((s, p) => s + p.files.length, 0);
console.log(
  `[acc] Wrote ${parts.length + 1} text files to handoff/text/ (${total} source files, max ${Math.round(MAX_BYTES / 1024)} KB each).`,
);
for (const n of ["acc-00-START-HERE.txt", ...names]) console.log(`  ${n}`);
