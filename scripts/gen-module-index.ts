/**
 * Generates src/modules/_generated.ts by globbing src/modules/<id>/module.ts.
 * Adding a module = creating a folder with a module.ts. Never edit _generated.ts by hand.
 */
import { readdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "src", "modules");
const dirs = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_"))
  .map((d) => d.name)
  .filter((name) => existsSync(join(root, name, "module.ts")))
  .sort();

const ident = (name: string) => "m_" + name.replace(/[^a-zA-Z0-9]/g, "_");
const out = `// AUTO-GENERATED by scripts/gen-module-index.ts — do not edit.
import type { AccModule } from "./types";
${dirs.map((d) => `import ${ident(d)} from "./${d}/module";`).join("\n")}

export const discoveredModules: AccModule[] = [${dirs.map(ident).join(", ")}];
`;

const target = join(root, "_generated.ts");
const prev = existsSync(target) ? readFileSync(target, "utf8") : "";
if (prev !== out) {
  writeFileSync(target, out);
  console.log(`[acc] module index: ${dirs.length} modules (${dirs.join(", ")})`);
}
